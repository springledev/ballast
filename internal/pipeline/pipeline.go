// Pipeline turns a configured service into a verified restic backup.
// It is the only real implementer of scheduler.Runner; tests and the
// scheduler's own unit tests use a stub instead.
type Pipeline struct {
	// DB is the Ballast database (inventory, engine runs).
	DB *sql.DB
	// Catalog is the loaded catalog registry (bundled + user entries).
	Catalog *catalog.Registry
	// Runner executes every restic/docker/dump subprocess. Its Redact
	// list must be the same secret list as Redact below (built once,
	// in the wiring).
	Runner *runner.Runner
	// CredDir is the resolved credential directory
	// (config.Config.CredentialsDir): destination password files live
	// here.
	CredDir string
	// OwnCredDir is where Ballast saves secrets it created itself
	// (config.Config.WritableCredentialsDir). A password file missing
	// from CredDir is looked for here, so a password generated by the
	// wizard is found under systemd too. Empty searches CredDir only.
	OwnCredDir string
	// WorkRoot is the parent of each service's stable per-run work
	// directory (<WorkRoot>/<service>), typically <DataDir>/work.
	WorkRoot string
	// KnownHostsFile is where SFTP destinations' server host keys are
	// remembered (backend.Resolver.KnownHostsFile), typically
	// <DataDir>/ssh/known_hosts.
	KnownHostsFile string
	// Notifier delivers run-outcome notifications; nil disables them.
	Notifier engine.Notifier
	// Log receives one plain-English line per notable event. Nil
	// means os.Stderr.
	Log io.Writer
	// Redact holds secret strings that must never reach Log or a
	// returned error's text (spec rule 2). Must be the same Set given
	// to Runner.Redact and scheduler.Coordinator.Redact.
	Redact *secret.Set

	// DockerStateDir holds the per-host ssh wrappers remote-ssh Docker
	// hosts use (dockerhost.Resolver.StateDir), typically
	// <DataDir>/ssh/docker-hosts.
	DockerStateDir string

	// ResticBin, DockerBin and PctBin override the restic/docker/pct
	// binaries; empty resolves against $PATH. Tests point these at
	// stubs.
	ResticBin, DockerBin, PctBin string

	// TargetParallel is how many of one service's destinations upload
	// and verify at the same time; zero or one means one at a time.
	TargetParallel int

	// Proxmox resolves the configured Proxmox connection for guest jobs
	// (spec §19.6); ProxmoxPoll overrides how often a running Proxmox
	// task is checked (tests only; zero means the default).
	Proxmox     proxmox.Resolver
	ProxmoxPoll time.Duration

	// RepoHealth, when set, clears a stale lock from this machine
	// before each upload and explains any lock it leaves alone (spec
	// §19.7). Nil skips the lock check.
	RepoHealth *repohealth.Checker

	logMu sync.Mutex
}

// Resolver returns the backend.Resolver this pipeline opens
// destination repositories with.
func (p *Pipeline) Resolver() backend.Resolver {
	return backend.Resolver{
		CredDirs:       []string{p.CredDir, p.OwnCredDir},
		Runner:         p.Runner,
		ResticBin:      p.ResticBin,
		Redact:         p.Redact,
		KnownHostsFile: p.KnownHostsFile,
	}
}

// DockerHosts returns the dockerhost.Resolver this pipeline reaches
// Docker hosts with. Remote-ssh hosts share KnownHostsFile with SFTP
// destinations: both are "machines Ballast has connected to".
func (p *Pipeline) DockerHosts() dockerhost.Resolver {
	return dockerhost.Resolver{
		CredDirs:       []string{p.CredDir, p.OwnCredDir},
		DockerBin:      p.DockerBin,
		StateDir:       p.DockerStateDir,
		KnownHostsFile: p.KnownHostsFile,
		Redact:         p.Redact,
	}
}

// Run backs up service: PREPARING → DUMPING → UPLOADING → VERIFYING →
// SUCCESS, or SUCCESS_UNVERIFIED (amber) when verification could not
// be completed, or FAILED/CANCELLED along the way.
//
// It returns a nil error only for engine.SUCCESS (scheduler.Runner's
// contract): SUCCESS_UNVERIFIED is always accompanied by a non-nil
// error, so a caller like `ballast run-due` can never mistake amber
// for a clean success. ctx cancellation is never swallowed: a run cut
// short transitions to CANCELLED and returns ctx's error.
func (p *Pipeline) Run(ctx context.Context, service string) (engine.State, error) {
	// Step 1 (spec plan): resolve configuration before a run exists.
	// A bad service/destination/catalog config is not a run — nothing
	// is persisted for it.
	svc, err := inventory.GetService(p.DB, service)
	if err != nil {
		return "", fmt.Errorf("service %s: %w", service, err)
	}
	if svc.IsGuestJob() {
		return p.runGuest(ctx, svc)
	}
	if svc.IsConfigSnapshot() {
		return p.runConfigSnapshot(ctx, svc)
	}
	var targets []*runTarget
	for _, t := range svc.EffectiveTargets() {
		dest, err := inventory.GetDestination(p.DB, t.Destination)
		if err != nil {
			return "", fmt.Errorf("service %s: %w", service, err)
		}
		targets = append(targets, &runTarget{target: t, dest: dest})
	}
	host, err := inventory.GetDockerHost(p.DB, svc.DockerHost)
	if err != nil {
		return "", fmt.Errorf("service %s: %w", service, err)
	}
	entry, ok := p.Catalog.Get(svc.CatalogEntry)
	if !ok {
		return "", fmt.Errorf("service %s: catalog entry %q is not loaded", service, svc.CatalogEntry)
	}
	m, err := engine.StartRun(p.DB, service)
	if err != nil {
		return "", fmt.Errorf("service %s: %w", service, err)
	}
	if p.Notifier != nil {
		m.SetNotifier(ctx, p.Notifier)
	}
	defer p.logNotifyErr(service, m)

	// fail is the single terminal-outcome path (spec plan hard rule):
	// a cancelled context always wins and transitions to CANCELLED,
	// returning ctx's own error; otherwise the run is FAILED with a
	// redacted, service-attributed detail.
	fail := func(cause error) (engine.State, error) {
		if ctx.Err() != nil {
			if terr := m.Transition(engine.CANCELLED, "cancelled: Ballast is shutting down"); terr != nil {
				p.logf("%s: recording cancellation: %v", service, terr)
			}
			p.logf("%s: run %d cancelled", service, m.Run().ID)
			return engine.CANCELLED, ensureServiceContext(service, ctx.Err())
		}
		err := ensureServiceContext(service, cause)
		detail := p.redact(err.Error())
		if terr := m.Transition(engine.FAILED, detail); terr != nil {
			p.logf("%s: recording failure: %v", service, terr)
		}
		p.logf("%s: run %d failed: %s", service, m.Run().ID, detail)
		return engine.FAILED, err
	}

	// PREPARING: build every dependency this run needs, and stage a
	// clean, stable-per-service work directory. The directory is
	// stable (not per-run) because restic groups retention by
	// path-set (spec §8): a per-run directory would defeat `forget`.
	// Wiping and recreating it here is safe because the Coordinator's
	// run lock is held for the whole call.
	if err := m.Transition(engine.PREPARING, "preparing"); err != nil {
		return fail(err)
	}
	// Discovery and secrets depend on the host's state on the day of
	// the run (a stopped container, a missing or loosened credential
	// file), not on configuration, so they fail inside the run: the
	// service goes red and a notification fires (spec §3).
	// The host's credential files are host state too: a missing or
	// loosened SSH key fails the run, not the configuration.
	docker, err := p.DockerHosts().Docker(host)
	if err != nil {
		return fail(err)
	}
	discovered, err := detect.ResolveDiscovery(ctx, p.Runner, docker, entry.Discovery, entry.ParamsWithDefaults(svc.Params))
	if err != nil {
		return fail(err)
	}
	if err := entry.Resolve(catalog.TemplateContext{Params: svc.Params, Services: svc.Containers, Discovery: discovered}); err != nil {
		return fail(fmt.Errorf("resolving catalog entry %q: %w", svc.CatalogEntry, err))
	}
	entry.AddExcludes(svc.Excludes)
	secrets, err := p.resolveSecrets(svc)
	if err != nil {
		return fail(err)
	}
	if err := entry.ResolveSecrets(secrets); err != nil {
		return fail(fmt.Errorf("resolving catalog entry %q: %w", svc.CatalogEntry, err))
	}
	strat, err := strategy.For(entry, strategy.Options{Runner: p.Runner, Docker: docker, PctBin: p.PctBin})
	if err != nil {
		return fail(err)
	}
	checkers, err := verify.For(entry, verify.Options{Runner: p.Runner, Docker: docker})
	if err != nil {
		return fail(err)
	}
	// Check on the service's own host that what will be read exists,
	// before the run touches anything (a wrong path must never cost a
	// stopped container).
	if pf, ok := strat.(strategy.Preflighter); ok {
		if err := pf.Preflight(ctx); err != nil {
			return fail(err)
		}
	}
	// SUCCESS is refused by the engine unless every declared method
	// and restic's read-back recorded a passing result (spec §17.6).
	m.RequireVerifications(append(entry.Verify.MethodList(), readBackMethod)...)
	// Credential files are read fresh for every run (inside Open): a
	// destination added, or a key file replaced, after Ballast started
	// must still be redacted. A destination that cannot be opened only
	// fails its own target; the others still get their backup.
	for _, rt := range targets {
		rt.repo, rt.err = p.Resolver().Open(rt.dest.Target())
	}
	if allFailed(targets) {
		return fail(targetsError(targets))
	}
	workDir := filepath.Join(p.WorkRoot, service)
	if err := os.RemoveAll(workDir); err != nil {
		return fail(fmt.Errorf("preparing work directory %s: %w", workDir, err))
	}
	if err := os.MkdirAll(workDir, 0o700); err != nil {
		return fail(fmt.Errorf("preparing work directory %s: %w", workDir, err))
	}

	// DUMPING: the artifacts are produced once, whatever the number of
	// targets (one stop/start window).
	if err := m.Transition(engine.DUMPING, "dumping"); err != nil {
		return fail(err)
	}
	res, err := strat.Backup(ctx, strategy.Request{WorkDir: workDir})
	if err != nil {
		return fail(err)
	}
	for _, rt := range targets {
		if rt.err == nil {
			rt.paths, rt.artifacts, rt.err = selectParts(res, rt.target)
		}
	}
	if allFailed(targets) {
		return fail(targetsError(targets))
	}

	// UPLOADING: every target gets its own snapshot.
	if err := m.Transition(engine.UPLOADING, "uploading"); err != nil {
		return fail(err)
	}
	p.forEachTarget(targets, func(rt *runTarget) {
		br, err := p.uploadTarget(ctx, service, rt, res)
		if err != nil {
			rt.err = err
			return
		}
		rt.snapshotID = br.SnapshotID
	})
	if ctx.Err() != nil {
		return fail(ctx.Err())
	}
	if allFailed(targets) {
		return fail(targetsError(targets))
	}
	for _, rt := range targets {
		if rt.snapshotID != "" {
			if err := m.SetSnapshotID(rt.snapshotID); err != nil {
				return fail(err)
			}
			break
		}
	}

	// VERIFYING (mandatory, spec §4.1: SUCCESS is unreachable without
	// it). Restore drills run once per artifact; restic's read-back
	// runs once per destination.
	if err := m.Transition(engine.VERIFYING, "verifying"); err != nil {
		return fail(err)
	}
	shared, foldArchive, err := p.runCheckers(ctx, service, entry, checkers, res)
	if err != nil {
		return fail(err)
	}
	p.forEachTarget(targets, func(rt *runTarget) {
		if rt.err == nil {
			rt.checks = p.targetChecks(ctx, service, rt, foldArchive)
		}
	})
	if ctx.Err() != nil {
		return fail(ctx.Err())
	}
	for _, c := range shared {
		if err := m.RecordVerification(c.rec); err != nil {
			return fail(err)
		}
	}
	for _, rt := range targets {
		for _, c := range rt.checks {
			if err := m.RecordVerification(c.rec); err != nil {
				return fail(err)
			}
		}
	}

	// Each target's own verdict: one target failing never hides
	// another's result (spec rule 3).
	sharedFail, sharedFailed := firstHardFailure(shared)
	for _, rt := range targets {
		switch failed, hard := firstHardFailure(rt.checks); {
		case rt.err != nil:
			rt.state, rt.detail = engine.FAILED, p.redact(rt.err.Error())
		case sharedFailed:
			rt.state, rt.detail = engine.FAILED, fmt.Sprintf("verification failed (%s): %s", sharedFail.rec.Method, sharedFail.rec.Detail)
		case hard:
			rt.state, rt.detail = engine.FAILED, fmt.Sprintf("verification failed (%s): %s", failed.rec.Method, failed.rec.Detail)
		case anyUnverifiable(rt.checks):
			rt.state, rt.detail = engine.SUCCESS_UNVERIFIED, "backup uploaded but could not be fully verified: "+unverifiableSummary(rt.checks)
		default:
			rt.state, rt.detail = engine.SUCCESS, "backup verified"
		}
		if err := m.RecordTarget(engine.TargetResult{Destination: rt.dest.Name, State: rt.state, SnapshotID: rt.snapshotID, Detail: rt.detail}); err != nil {
			return fail(err)
		}
	}
	// Retention cleanup only for a target with a verified SUCCESS, and
	// never lets its own failure change the run's outcome (spec plan
	// step 8).
	defer p.retainTargets(ctx, service, targets)

	if anyTargetFailed(targets) {
		return fail(targetsError(targets))
	}
	if anyTargetUnverified(targets) {
		detail := targetsSummary(targets, engine.SUCCESS_UNVERIFIED)
		if err := m.Transition(engine.SUCCESS_UNVERIFIED, detail); err != nil {
			return fail(err)
		}
		p.logf("%s: run %d succeeded but is unverified (amber): %s", service, m.Run().ID, detail)
		return engine.SUCCESS_UNVERIFIED, ensureServiceContext(service, fmt.Errorf("%s", detail))
	}
	if err := m.Transition(engine.SUCCESS, "backup verified"); err != nil {
		return fail(err)
	}
	p.logf("%s: run %d succeeded and is verified", service, m.Run().ID)
	return engine.SUCCESS, nil
}

// verifyCheck pairs a persisted verification record with whether it
// represents an "impossible to verify" outcome (destination
// unreadable) rather than a real fail/pass verdict — the distinction
// that decides FAILED vs SUCCESS_UNVERIFIED.
type verifyCheck struct {
	rec          engine.VerificationRecord
	unverifiable bool
}

// readBackMethod is the method name of restic's own read-back check,
// which every run records.
const readBackMethod = "restic-read-back"

// runCheckers runs every checker the catalog declares, in order, once
// per run (a restore drill checks the artifacts, which are the same
// whatever the number of destinations). foldArchive reports that an
// archive-integrity check of a zero-artifact files backup had nothing
// to inspect: it is folded into each target's read-back result instead
// (step 11 user decision) rather than reporting a silent failure.
func (p *Pipeline) runCheckers(ctx context.Context, service string, entry *catalog.Entry, checkers []verify.Checker, res *strategy.Result) (checks []verifyCheck, foldArchive bool, err error) {
	var sourceContainer string
	if len(entry.Backup.Dumps) > 0 {
		sourceContainer = entry.Backup.Dumps[0].Container
	}
	for _, checker := range checkers {
		if len(res.Artifacts) == 0 && checker.Method() == verify.MethodArchiveIntegrity {
			foldArchive = true
			continue
		}
		vres := checker.Check(ctx, verify.Request{
			Service:         service,
			Artifacts:       res.Artifacts,
			SourceContainer: sourceContainer,
		})
		if err := ctx.Err(); err != nil {
			return nil, false, err
		}
		checks = append(checks, verifyCheck{rec: p.toRecord(vres)})
	}
	return checks, foldArchive, nil
}

// targetChecks runs the checks that belong to one destination: restic's
// own read-back, which proves the backup there is restorable at all, is
// recorded as an explicit result either way — never silently skipped.
func (p *Pipeline) targetChecks(ctx context.Context, service string, rt *runTarget, foldArchive bool) []verifyCheck {
	var readBack verifyCheck
	shared := repoLock(rt.repo.Location)
	shared.RLock()
	rb, rbErr := rt.repo.ReadBack(ctx, rt.snapshotID)
	shared.RUnlock()
	switch {
	case rbErr != nil:
		readBack = verifyCheck{
			rec: engine.VerificationRecord{
				Method: readBackMethod,
				Passed: false,
				Detail: p.redact(fmt.Sprintf("could not read the backup back from the destination to confirm it is restorable: %v", rbErr)),
			},
			unverifiable: true,
		}
	default:
		readBack = verifyCheck{
			rec: engine.VerificationRecord{
				Method: readBackMethod,
				Passed: true,
				Detail: fmt.Sprintf("read %d sample file(s) back from snapshot %s to confirm the backup is restorable", len(rb.Samples), rb.Snapshot.ShortID),
			},
		}
	}
	readBack.rec.Target = rt.dest.Name
	checks := []verifyCheck{readBack}
	if foldArchive {
		checks = append(checks, verifyCheck{
			rec: engine.VerificationRecord{
				Target:  rt.dest.Name,
				Method:  verify.MethodArchiveIntegrity,
				Passed:  readBack.rec.Passed,
				Warning: readBack.rec.Warning,
				Detail:  "No archive files were produced (files are uploaded directly); integrity was proven by reading the files back from the backup.",
			},
			unverifiable: readBack.unverifiable,
		})
	}
	return checks
}

// toRecord converts a verify.Result into the engine's persisted
// record shape, redacting Detail/Output/Warning (internal/verify's
// checkers already redact command stderr via the runner, but this is
// the last line of defence before the DB, matching spec rule 2).
func (p *Pipeline) toRecord(r verify.Result) engine.VerificationRecord {
	return engine.VerificationRecord{
		Method:   r.Method,
		Passed:   r.Passed,
		Warning:  p.redact(r.Warning),
		Detail:   p.redact(r.Detail),
		Output:   p.redact(r.Output),
		Duration: r.Duration,
	}
}

// firstHardFailure returns the first check that is neither passed nor
// merely unverifiable — a real verification failure.
func firstHardFailure(checks []verifyCheck) (verifyCheck, bool) {
	for _, c := range checks {
		if !c.rec.Passed && !c.unverifiable {
			return c, true
		}
	}
	return verifyCheck{}, false
}

// anyUnverifiable reports whether any check could not be completed
// (destination unreadable), which makes the run amber rather than red
// or green.
func anyUnverifiable(checks []verifyCheck) bool {
	for _, c := range checks {
		if c.unverifiable {
			return true
		}
	}
	return false
}

// unverifiableSummary describes every unverifiable check, for the
// SUCCESS_UNVERIFIED detail and returned error.
func unverifiableSummary(checks []verifyCheck) string {
	var parts []string
	for _, c := range checks {
		if c.unverifiable {
			parts = append(parts, c.rec.Method+": "+c.rec.Detail)
		}
	}
	return strings.Join(parts, "; ")
}

// artifactPaths extracts every strategy artifact's file path.
func artifactPaths(artifacts []strategy.Artifact) []string {
	out := make([]string, 0, len(artifacts))
	for _, a := range artifacts {
		out = append(out, a.Path)
	}
	return out
}

// ensureServiceContext guarantees err's text names service, without
// doubling an existing "service <name>:" prefix that most internal
// package errors already carry.
func ensureServiceContext(service string, err error) error {
	prefix := "service " + service + ":"
	if strings.HasPrefix(err.Error(), prefix) {
		return err
	}
	return fmt.Errorf("%s %w", prefix, err)
}

// redact scrubs every configured secret from s.
func (p *Pipeline) redact(s string) string {
	return p.Redact.Redact(s)
}

// resolveSecrets reads the plaintext value of every secret svc
// declares (Service.Secrets: {{ .Secrets.NAME }} name -> credential
// file name) from the credential directory, exactly like the
// destination password file above, and immediately registers each
// value with p.Redact — before the dump command that needs it ever
// runs, so a secret can never reach a log line or error even if the
// run that needed it fails on its very first step. Read fresh for
// every run, for the same reason the destination password is: a
// secret added, or its file replaced, after Ballast started must
// still be picked up and redacted.
func (p *Pipeline) resolveSecrets(svc inventory.Service) (map[string]string, error) {
	if len(svc.Secrets) == 0 {
		return nil, nil
	}
	out := make(map[string]string, len(svc.Secrets))
	for name, cred := range svc.Secrets {
		if path, key, ok := inventory.ParseEnvRef(cred); ok {
			v, err := dotenv.Lookup(path, key)
			if err != nil {
				return nil, fmt.Errorf("secret %q: could not read %s from %s: %w", name, key, path, err)
			}
			p.Redact.Add(v)
			out[name] = v
			continue
		}
		dir := runner.FindCredentialDir(cred, p.CredDir, p.OwnCredDir)
		v, err := runner.LoadCredentialValue(dir, cred)
		if err != nil {
			return nil, fmt.Errorf("secret %q: %w", name, err)
		}
		p.Redact.Add(v)
		out[name] = v
	}
	return out, nil
}

// logf writes one redacted, plain-English line to Log (os.Stderr when
// unset).
func (p *Pipeline) logf(format string, args ...any) {
	w := p.Log
	if w == nil {
		w = os.Stderr
	}
	p.logMu.Lock()
	defer p.logMu.Unlock()
	fmt.Fprintln(w, p.redact(fmt.Sprintf("ballast: "+format, args...)))
}

// logNotifyErr logs the run's most recent notification delivery
// failure, if any, without ever masking the run's own outcome (which
// is already committed by the time this runs).
func (p *Pipeline) logNotifyErr(service string, m *engine.Machine) {
	if err := m.NotifyErr(); err != nil {
		p.logf("%s: notification delivery failed (run outcome unaffected): %v", service, err)
	}
}
